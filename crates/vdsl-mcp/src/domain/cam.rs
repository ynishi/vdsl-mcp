/// Lua DSL cam script template. Placeholders use `__CAM_*__` sentinel form to
/// avoid collisions with `${...}` style Lua string formatting patterns.
///
/// Placeholders:
/// - `__CAM_OUT__`          — absolute path of the output file (header comment)
/// - `__CAM_PERSONA_ID__`   — persona id slug
/// - `__CAM_TOPIC__`        — topic slug
/// - `__CAM_SCENE__`        — scene description (Lua-escaped, header comment)
/// - `__CAM_BASE_SNIPPET__` — persona base snippet (resolved from cam-vdsl bases)
/// - `__CAM_SHOTS_TABLE__`  — Lua table literal for shots array
const CAM_LUA_TEMPLATE: &str = r#"--- __CAM_OUT__ — __CAM_PERSONA_ID__ cam (__CAM_TOPIC__)
-- Generated by vdsl_cam_lua_init.
-- Scene: __CAM_SCENE__
local vdsl = require("vdsl")

-- Overlay user catalogs (project-personal vocabulary).
-- Directory is git-untracked, any literal stays in user-personal space.
-- No-op if the directory or specific catalog files don't exist.
local home = os.getenv("HOME")
if home and home ~= "" then
  vdsl.use_catalogs(home .. "/.claude/skills/cam-vdsl/catalogs")
end

local C = vdsl.catalogs

local w = vdsl.world {
  model     = "waiIllustrious_v16.safetensors",
  clip_skip = 2,
}

local neg = C.quality.neg_default
          + C.quality.neg_anatomy
          + C.quality.neg_face
          + C.figure.expression.bad_face

__CAM_BASE_SNIPPET__

local common_cam = C.camera.medium_shot
                 + C.camera.eye_level
                 + C.camera.portrait_lens
                 + C.camera.shallow_dof

local shots = __CAM_SHOTS_TABLE__

for _, s in ipairs(shots) do
  local result = vdsl.render {
    world   = w,
    cast    = { vdsl.cast { subject = base:with((s.trait or vdsl.trait("")) + common_cam), negative = neg } },
    sampler = "euler_ancestral",
    steps   = 25,
    cfg     = 6.0,
    seed    = s.seed,
    size    = { 832, 1216 },
  }
  vdsl.emit(s.name, result)
end
"#;

