/// Returns today's date in compact `YYMMDD` format (local time).
fn today_compact() -> String {
    chrono::Local::now().format("%y%m%d").to_string()
}

/// Returns today's date in `YYYYMM` format (local time), used for default shot naming.
fn today_yyyymm() -> String {
    chrono::Local::now().format("%Y%m").to_string()
}

/// Validates that `s` is a non-empty slug consisting only of `[a-zA-Z0-9_-]`.
fn validate_slug(s: &str) -> bool {
    !s.is_empty()
        && s.chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
}

/// Escapes `s` for use inside a Lua double-quoted string literal.
/// Replaces `\` → `\\` and `"` → `\"`.
/// Newlines are not allowed (callers must validate before calling).
fn lua_str_escape(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Resolves the base snippet for `persona_id` using the 3-stage fallback defined
/// in cam-vdsl SKILL §"Persona 別 base subject の解決":
///
/// 1. `~/.claude/skills/cam-vdsl/bases/<persona_id>.lua`
/// 2. `~/.claude/skills/snap-<persona_id>/<persona_id>_base.lua` (legacy)
/// 3. Thin default base literal
///
/// Returns `(snippet, source_label)` where `source_label` is either
/// `"file:<path>"` or `"fallback:default"`.
///
/// IO errors that are `NotFound` or `PermissionDenied` are silently absorbed
/// and trigger fallback. Other IO errors propagate as `CamLuaScaffoldError::Io`.
fn resolve_base_snippet(persona_id: &str) -> Result<(String, String), CamLuaScaffoldError> {
    let home = dirs::home_dir().ok_or(CamLuaScaffoldError::NoHomeDir)?;

    // Stage 1: ~/.claude/skills/cam-vdsl/bases/<persona_id>.lua
    let stage1_path = home
        .join(".claude")
        .join("skills")
        .join("cam-vdsl")
        .join("bases")
        .join(format!("{persona_id}.lua"));
    match std::fs::read_to_string(&stage1_path) {
        Ok(snippet) => {
            let source = format!("file:{}", stage1_path.display());
            return Ok((snippet, source));
        }
        Err(e)
            if e.kind() == std::io::ErrorKind::NotFound
                || e.kind() == std::io::ErrorKind::PermissionDenied => {}
        Err(e) => return Err(CamLuaScaffoldError::Io(e)),
    }

    // Stage 2: ~/.claude/skills/snap-<persona_id>/<persona_id>_base.lua (legacy)
    let stage2_path = home
        .join(".claude")
        .join("skills")
        .join(format!("snap-{persona_id}"))
        .join(format!("{persona_id}_base.lua"));
    match std::fs::read_to_string(&stage2_path) {
        Ok(snippet) => {
            let source = format!("file:{}", stage2_path.display());
            // The legacy base file uses `local <persona_id>_base = ...` as the identifier.
            // The template expects `base`, so we append an alias line.
            let alias_id = format!("{persona_id}_base");
            let snippet = if snippet.contains(&format!("local {alias_id}")) {
                format!("{snippet}\nlocal base = {alias_id}")
            } else {
                snippet
            };
            return Ok((snippet, source));
        }
        Err(e)
            if e.kind() == std::io::ErrorKind::NotFound
                || e.kind() == std::io::ErrorKind::PermissionDenied => {}
        Err(e) => return Err(CamLuaScaffoldError::Io(e)),
    }

    // Stage 3: thin default base
    let default_snippet = r#"local base = vdsl.subject("1girl, solo, 20 years old")
  :with(C.figure.expression.smile)
  :quality("high")
  :style("photo")"#
        .to_string();
    Ok((default_snippet, "fallback:default".to_string()))
}

/// Builds a Lua table literal for the shots array.
///
/// Each shot produces a table entry:
/// ```lua
/// { name = "...", seed = N, trait = <trait_dsl literal> }
/// ```
/// `trait_dsl` is emitted **verbatim** as a Lua expression so callers can
/// pass catalog references (`"C.figure.hair.long"`), composed expressions
/// (`"C.figure.clothing.t_shirt + C.figure.expression.smile"`), or raw-text
/// wrappers (`"vdsl.trait(\"red dress, smiling\")"`). When `trait_dsl` is
/// empty the `trait` field is set to `nil`.
fn build_shots_table(shots: &[CamShotSpec]) -> String {
    let mut entries: Vec<String> = Vec::new();
    for s in shots {
        let name_escaped = lua_str_escape(&s.name);
        let trait_val = if s.trait_dsl.is_empty() {
            "nil".to_string()
        } else {
            // Pass-through: trait_dsl is a Lua expression, not a raw string.
            // Callers wanting raw text use `vdsl.trait("...")` explicitly.
            s.trait_dsl.clone()
        };
        entries.push(format!(
            "  {{ name = \"{name_escaped}\", seed = {seed}, trait = {trait_val} }}",
            seed = s.seed,
        ));
    }
    format!("{{\n{}\n}}", entries.join(",\n"))
}

