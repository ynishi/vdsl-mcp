/// Scaffold a new cam Lua DSL script at `<root>/<persona_id>_cam_<topic>.lua`.
///
/// The generated file uses `vdsl.render` loops following the cam-vdsl SKILL
/// §手順 7 structure. The persona base subject snippet is resolved from
/// `~/.claude/skills/cam-vdsl/bases/<persona_id>.lua` (3-stage fallback).
///
/// # Arguments
///
/// * `persona_id` — persona slug (must match `^[a-zA-Z0-9_-]+$`)
/// * `scene` — scene description embedded in header comment (no newlines)
/// * `shots` — shot specifications; when `None` a single default shot is generated
/// * `topic` — topic slug; when `None` defaults to `snap_YYMMDD`
/// * `root` — projects root directory (caller typically passes result of `resolve_projects_root`)
/// * `overwrite` — when `false` return an error if target already exists
///
/// # Returns
///
/// A [`CamLuaScaffoldResult`] with the absolute path of the created/overwritten
/// script, whether it was newly created, and which base-resolution path was taken.
///
/// # Errors
///
/// - [`CamLuaScaffoldError::InvalidPersonaId`] — persona_id fails slug validation
/// - [`CamLuaScaffoldError::InvalidTopic`] — topic fails slug validation
/// - [`CamLuaScaffoldError::InvalidShotName`] — a shot name fails slug validation
/// - [`CamLuaScaffoldError::AlreadyExists`] — target exists and `overwrite` is `false`
/// - [`CamLuaScaffoldError::Io`] — directory creation or file write fails
/// - [`CamLuaScaffoldError::NoHomeDir`] — home directory could not be resolved
pub fn scaffold_cam_lua(
    persona_id: &str,
    scene: &str,
    shots: Option<&[CamShotSpec]>,
    topic: Option<&str>,
    root: &Path,
    overwrite: bool,
) -> Result<CamLuaScaffoldResult, CamLuaScaffoldError> {
    // Validate persona_id
    if !validate_slug(persona_id) {
        return Err(CamLuaScaffoldError::InvalidPersonaId(format!(
            "'{persona_id}' must be non-empty and match [a-zA-Z0-9_-]"
        )));
    }

    // Resolve topic
    let resolved_topic = match topic {
        Some(t) => {
            if !validate_slug(t) {
                return Err(CamLuaScaffoldError::InvalidTopic(format!(
                    "'{t}' must be non-empty and match [a-zA-Z0-9_-]"
                )));
            }
            t.to_string()
        }
        None => format!("snap_{}", today_compact()),
    };

    // Validate scene (no newlines allowed — would break Lua line comment)
    if scene.contains('\n') || scene.contains('\r') {
        return Err(CamLuaScaffoldError::InvalidTopic(
            "scene must not contain newlines".to_string(),
        ));
    }

    // Resolve shots (build or use single-shot fallback)
    let default_shot;
    let shots_slice: &[CamShotSpec] = match shots {
        Some(s) => {
            // Validate all shot names
            for shot in s.iter() {
                if !validate_slug(&shot.name) {
                    return Err(CamLuaScaffoldError::InvalidShotName(format!(
                        "shot name '{}' must be non-empty and match [a-zA-Z0-9_-]",
                        shot.name
                    )));
                }
                // Also reject newlines in trait_dsl
                if shot.trait_dsl.contains('\n') || shot.trait_dsl.contains('\r') {
                    return Err(CamLuaScaffoldError::InvalidShotName(format!(
                        "shot '{}' trait_dsl must not contain newlines",
                        shot.name
                    )));
                }
            }
            s
        }
        None => {
            let yyyymm = today_yyyymm();
            default_shot = [CamShotSpec {
                name: format!("{persona_id}-{yyyymm}-V1-{resolved_topic}"),
                seed: 1234,
                trait_dsl: String::new(),
            }];
            &default_shot
        }
    };

    // Determine target path
    let target_path = root.join(format!("{persona_id}_cam_{resolved_topic}.lua"));

    let was_existing = target_path.exists();
    if was_existing && !overwrite {
        return Err(CamLuaScaffoldError::AlreadyExists(
            target_path.display().to_string(),
        ));
    }

    // Resolve base snippet (crux: persona_id-driven, never fixed skeleton)
    let (base_snippet, base_source) = resolve_base_snippet(persona_id)?;

    // auto-mkdir (crux: server-side Write + auto-mkdir)
    std::fs::create_dir_all(root)?;

    // Build shots table Lua literal
    let shots_table = build_shots_table(shots_slice);

    // Expand template
    let out_path_str = target_path.display().to_string();
    let scene_escaped = lua_str_escape(scene);
    let content = CAM_LUA_TEMPLATE
        .replace("__CAM_OUT__", &out_path_str)
        .replace("__CAM_PERSONA_ID__", persona_id)
        .replace("__CAM_TOPIC__", &resolved_topic)
        .replace("__CAM_SCENE__", &scene_escaped)
        .replace("__CAM_BASE_SNIPPET__", &base_snippet)
        .replace("__CAM_SHOTS_TABLE__", &shots_table);

    std::fs::write(&target_path, &content)?;

    Ok(CamLuaScaffoldResult {
        script_file: target_path,
        file_created: !was_existing,
        base_source,
    })
}

