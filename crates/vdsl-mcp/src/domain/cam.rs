/// Specification for a single shot in a cam sequence.
#[derive(Debug, Clone)]
pub struct CamShotSpec {
    /// Shot name (filename-safe: `[a-zA-Z0-9_-]` only).
    pub name: String,
    /// RNG seed for this shot.
    pub seed: i64,
    /// Trait DSL expression string appended to base subject. May be empty.
    pub trait_dsl: String,
}

/// Result returned by a successful [`scaffold_cam_lua`] call.
#[derive(Debug, serde::Serialize)]
pub struct CamLuaScaffoldResult {
    /// Absolute path of the created (or overwritten) Lua script.
    pub script_file: PathBuf,
    /// `true` if the file was newly created; `false` if it was overwritten
    /// (only possible when `overwrite=true`).
    pub file_created: bool,
    /// Describes which base-resolution path was taken.
    /// - `"file:<path>"` — base snippet read from a file
    /// - `"fallback:default"` — thin default base was used
    pub base_source: String,
}

/// Errors that can occur when scaffolding a new cam Lua script.
#[derive(Debug, thiserror::Error)]
pub enum CamLuaScaffoldError {
    /// The persona_id is invalid (empty or contains characters outside `[a-zA-Z0-9_-]`).
    #[error("invalid persona_id: {0}")]
    InvalidPersonaId(String),

    /// The topic is invalid (empty or contains characters outside `[a-zA-Z0-9_-]`).
    #[error("invalid topic: {0}")]
    InvalidTopic(String),

    /// A shot name is invalid (must be filename-safe: `[a-zA-Z0-9_-]` only).
    #[error("invalid shot name: {0}")]
    InvalidShotName(String),

    /// A cam Lua file already exists at the target path and `overwrite` was not requested.
    #[error("cam script '{0}' already exists (pass overwrite=true to force)")]
    AlreadyExists(String),

    /// An I/O error occurred while creating directories or writing the file.
    #[error("I/O error: {0}")]
    Io(#[from] std::io::Error),

    /// The home directory could not be resolved (needed for base snippet path resolution).
    #[error("home directory not found")]
    NoHomeDir,
}

